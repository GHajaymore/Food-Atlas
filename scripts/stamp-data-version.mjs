/**
 * Stamp the published data with a version taken from its own contents.
 *
 *   node scripts/stamp-data-version.mjs
 *
 * Runs first in `npm run build`, before the bundle is compiled, because the version has to
 * be inside the bundle that asks for the data.
 *
 * ## What this fixes
 *
 * `_headers` served `/data/*` as `max-age=3600, stale-while-revalidate=604800`, with a
 * comment saying "an ingest run reaches everybody within the hour". That is not what
 * stale-while-revalidate does. It serves the **old** copy to the first visit after the
 * hour and fetches the new one in the background, so a reader sees the correction one
 * visit later — and a reader who comes once a week never sees anything newer than a week.
 *
 * Ajay hit exactly that: the day after 37 records stopped being labelled "Authentic", he
 * was still shown a dish scored 29 and called authenticated. Nothing was wrong with the
 * atlas; he was being served the previous week's catalogue, which is worse, because a
 * correction that takes a week to arrive is not really a correction.
 *
 * ## How
 *
 * The version is a hash of the published data itself, so it changes exactly when the data
 * changes and never otherwise. The app appends it to every data URL, which makes a
 * corrected file a *different address* — a cache cannot serve the old one, and there is no
 * stale window at all. The files can then be cached hard, because the address of a given
 * copy never stops being right about its contents.
 *
 * The generated module is committed so a build from a clean checkout is reproducible.
 */

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DATA = resolve(HERE, '../public/data');
const TARGET = resolve(HERE, '../src/data/version.ts');

/** Sorted, so the same data hashes the same however the directory is listed. */
const files = readdirSync(DATA).filter((name) => name.endsWith('.json')).sort();

const hash = createHash('sha256');
for (const name of files) {
  hash.update(name);
  hash.update(readFileSync(resolve(DATA, name)));
}
/* Copy shipped per locale is data too: a corrected sentence must reach a reader as
   quickly as a corrected record. */
const COPY = resolve(DATA, 'copy');
let copies = [];
try {
  copies = readdirSync(COPY).filter((name) => name.endsWith('.json')).sort();
} catch {
  /* Written later in the build on a clean tree; absent is not an error. */
}
for (const name of copies) {
  hash.update(`copy/${name}`);
  hash.update(readFileSync(resolve(COPY, name)));
}

const version = hash.digest('hex').slice(0, 12);

const module = `/**
 * The published data's version — generated by \`scripts/stamp-data-version.mjs\`.
 *
 * Do not edit. It is a hash of everything in \`public/data\`, and it is appended to every
 * data URL the app fetches so that corrected data arrives at a new address. See the script
 * for why that matters more than it sounds: without it a reader can be served a week-old
 * catalogue and shown badges the atlas has already withdrawn.
 */
export const DATA_VERSION = '${version}';
`;

const existing = (() => {
  try {
    return readFileSync(TARGET, 'utf8');
  } catch {
    return '';
  }
})();

if (existing !== module) writeFileSync(TARGET, module);

process.stdout.write(
  `stamp-data-version: ${version} over ${files.length} data files and ${copies.length} copy files` +
    `${existing === module ? ' (unchanged)' : ''}\n`,
);
