/**
 * Take eleven languages out of the JavaScript bundle.
 *
 *   node scripts/split-catalogues.mjs        (runs as part of `npm run build`)
 *
 * `src/i18n/catalogues.ts` is 895 KB of source — 45% of everything in `src/` and `app/`
 * — and about **15% of the bundle on the wire** once compressed. Every reader downloaded
 * twelve languages in order to read in one.
 *
 * This writes each non-English catalogue to `public/data/copy/<locale>.json`, fetched
 * only by a reader who actually reads in that language. English stays compiled in: it is
 * the fallback behind every key, so it has to be there before anything can render.
 *
 * ## The manifest, and why the numbers are precomputed
 *
 * Two things were derived from having all twelve catalogues in memory:
 *
 *   - `UI_LOCALES`, from `Object.keys(CATALOGUES)`
 *   - `translationCoverage(locale)`, which counts how many keys a catalogue actually
 *     translates — the figure the language picker shows as "60%"
 *
 * Neither can survive lazy loading, and the second is the dangerous one: a picker that
 * quietly reported the wrong completeness would be exactly the kind of confident-but-wrong
 * number this project refuses to print. So both are computed here, from the real
 * catalogues, and written to `src/i18n/manifest.ts` as data.
 *
 * That file is generated and committed. `__tests__` checks it still matches the
 * catalogues, so if somebody edits a translation and does not re-run this, the suite says
 * so rather than the picker drifting silently.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CATALOGUES } from '../src/i18n/catalogues.ts';
import { EN } from '../src/i18n/copy.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../public/data/copy');
const MANIFEST = resolve(HERE, '../src/i18n/manifest.ts');

/**
 * The share of the chrome a catalogue actually translates.
 *
 * Kept identical to what `translationCoverage` did when it could read the catalogues
 * directly: a key counts only if it is a non-empty string *and differs from English*, so
 * a catalogue that copies the English word does not inflate its own figure.
 */
const coverageOf = (catalogue) => {
  const keys = Object.keys(EN);
  const done = keys.filter((key) => {
    const value = catalogue[key];
    return typeof value === 'string' && value.trim() !== '' && value !== EN[key];
  });
  return done.length / keys.length;
};

const main = async () => {
  await mkdir(OUT, { recursive: true });

  const codes = Object.keys(CATALOGUES);
  const coverage = {};
  let written = 0;

  for (const code of codes) {
    const catalogue = CATALOGUES[code];
    coverage[code] = Number(coverageOf(catalogue).toFixed(6));
    /* No indentation: this is served, not read. */
    await writeFile(resolve(OUT, `${code}.json`), JSON.stringify(catalogue), 'utf8');
    written += 1;
  }

  const manifest = [
    '/**',
    ' * Generated by `scripts/split-catalogues.mjs`. Do not edit by hand.',
    ' *',
    ' * The two things the app needs to know about its twelve languages without holding all',
    ' * twelve in the bundle: which they are, and how complete each one is. The strings',
    ' * themselves are fetched per locale from `/data/copy/<locale>.json`.',
    ' *',
    ' * A test asserts these numbers still match `catalogues.ts`, so editing a translation',
    ' * without re-running the script fails the suite rather than drifting quietly into a',
    ' * language picker that reports a completeness nobody measured.',
    ' */',
    '',
    '/** Every locale with a catalogue, English excluded — it is compiled in. */',
    `export const LOCALE_CODES: readonly string[] = ${JSON.stringify(codes)};`,
    '',
    '/** How much of the chrome each locale actually translates, 0 to 1. */',
    'export const COVERAGE: Readonly<Record<string, number>> = Object.freeze(',
    `  ${JSON.stringify(coverage, null, 2).split('\n').join('\n  ')},`,
    ');',
    '',
  ].join('\n');

  await writeFile(MANIFEST, manifest, 'utf8');

  process.stdout.write(
    `Wrote ${written} catalogues to public/data/copy/ and the manifest for ${codes.length} locales.\n`,
  );
};

main().catch((error) => {
  process.stderr.write(`\nCatalogue split failed: ${error.message}\n`);
  process.exitCode = 1;
});
